namespace CompilerProject.Models
{
    /// <summary>
    /// تصنيفات الرموز المعجمية (Token Types) للغة البرمجة العربية
    /// Reference: قواعد لغة البرمجة العربية - جامعة إب (ص 1 - 8)
    /// </summary>
    public enum TokenType
    {
        // الكلمات المحجوزة في اللغة (Keywords)
        Keyword,

        // المعرفات (أسماء البرامج، المتغيرات، الثوابت، الأنواع، الإجراءات، الحقول)
        Identifier,

        // الأعداد (أعداد صحيحة وحقيقية)
        Number,

        // السلاسل الرمزية النصية المحصورة بين " "
        String,

        // الرموز المفردة المحصورة بين ' '
        Char,

        // العمليات الحسابية والمنطقية والمقارنة (+, -, *, /, \, %, ^, ==, !=, <, >, <=, >=, &&, ||, !)
        Operator,

        // الرموز الطرفية والمحددات (؛, :, ., ,, =, {, }, [, ], (, ))
        Symbol,

        // نهاية الملف المصدري
        EndOfFile
    }
}
